import { writeFile } from 'node:fs/promises';
const response = await fetch('https://fonts.googleapis.com/css2?family=Barlow+Condensed:wght@700&display=swap', { headers: { 'User-Agent': 'Mozilla/5.0 Chrome/130.0.0.0' } });
if (!response.ok) throw new Error('Display font request failed');
const css = await response.text();
const url = css.split('/* latin */').at(-1).match(/url\((https[^)]+)\)/)?.[1];
if (!url) throw new Error('Font file missing');
const font = await fetch(url);
if (!font.ok) throw new Error('Font download failed');
await writeFile(new URL('../public/fonts/barlow-condensed.woff2', import.meta.url), Buffer.from(await font.arrayBuffer()));
const license = await fetch('https://raw.githubusercontent.com/google/fonts/main/ofl/barlowcondensed/OFL.txt');
if (!license.ok) throw new Error('Font license download failed');
await writeFile(new URL('../public/fonts/barlowcondensed-OFL.txt', import.meta.url), await license.text());
console.log('Saved Barlow Condensed and its font license.');
